"""One-at-a-time layout and the teaching tools: questions appear one by one in working order, answers are
checked as you go, wrong tries get a nudge without the answer, per-question hints, the finished sheet is scored
on first tries; plus your-own-problem, share links, printing and Present mode."""
import os, sys, re
from playwright.sync_api import sync_playwright
URL=os.environ.get('SUBNET_URL','file://'+os.path.abspath(os.path.join(os.path.dirname(__file__),'..','index.html')))
fails=[]
def ok(c,msg):
    print(('  ✓ ' if c else '  ✗ ')+msg)
    if not c: fails.append(msg)
def answers(pg): return pg.evaluate("window.SS.state.q.fields.map(f=>f.type==='choice'?f.answer:window.SS.show(f))")
def answer(pg,a):
    if pg.locator('#fcard .choice').count(): pg.click(f'#fcard .choice[data-v="{a}"]')
    else: pg.fill('#fin',a.replace(',','')); pg.press('#fin','Enter')
with sync_playwright() as pw:
    b=pw.chromium.launch(); pg=b.new_page(viewport={'width':1300,'height':1100}); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(URL); pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(300)
    print('One at a time')
    pg.evaluate("window.SS.next(window.SS.genSheet({ip:'10.10.10.18',p:29,asPrefix:true}))")
    ok(pg.is_visible('#fcard') and pg.is_hidden('#fields') and pg.locator('#fcard').count()==1,'worksheet starts with a single question showing, not the whole sheet')
    order=pg.evaluate("window.SS.state.q.fields.map(f=>f.label)")
    ok(order[:4]==['Subnet mask (dotted decimal)','Subnet mask (binary)','Network increment','Hosts per network (2ʰ − 2)'] and order[-1]=='Total networks (2ⁿ)','order: mask, binary, increment, hosts … total networks last')
    seen=[]; ans=answers(pg)
    for i,a in enumerate(ans):
        seen.append(pg.inner_text('.fc-q'))
        if i==4: ok(pg.locator('.fs-chart').count()==1 and pg.locator('.fs-cur').count()==1,'the chart appears when you reach it, with the current cell marked')
        answer(pg,a); pg.wait_for_timeout(30)
        if i==1: ok(pg.locator('.fs-row').count()==2 and '11111000' in pg.inner_text('.fsheet'),'answered questions collect in the sheet above')
    ok(seen==order,'questions appear in exactly that order, one after another')
    ok('good' in pg.get_attribute('#feedback','class') and '+10' in pg.inner_text('#feedback'),'a perfect run scores +10')
    ok(pg.locator('#fcard').count()==0 and pg.locator('.fs-row').count()==len([l for l in order if not l.startswith('Row')]),'finished sheet shows every answer')
    pg.click('#checkBtn')
    print('Mistakes and hints')
    pg.evaluate("window.SS.next(window.SS.genSheet({ip:'10.10.10.15',p:28,asPrefix:false}))")
    ans=answers(pg)
    answer(pg,ans[0]); answer(pg,ans[1])
    pg.fill('#fin','240'); pg.press('#fin','Enter'); pg.wait_for_timeout(50)
    msg=pg.inner_text('.fc-msg')
    ok('mask octet' in msg and '16' not in re.sub(r'256 − 240','',msg),f'a wrong try gets a nudge, with the answer hidden: “{msg[:70]}…”')
    ok(pg.is_visible('#freveal') and pg.inner_text('.fc-q')=='Network increment','you stay on the question to try again, and can ask to see the answer')
    ok(pg.evaluate("window.SS.getWeak().wrong_inc&&window.SS.getWeak().wrong_inc.n")==1,'the mistake is logged to weak spots')
    answer(pg,'16'); ok(pg.inner_text('.fc-q')=='Hosts per network (2ʰ − 2)','fixing it moves on')
    ok(pg.locator('.fs-row.miss').count()==1,'the missed question is marked in the sheet')
    pg.click('#fhint'); ok(pg.locator('.fc-steps').count()==1,'Hint opens steps for just this question')
    steps=pg.evaluate("window.SS.getFlow().groups[window.SS.getFlow().k].map(s=>s.kind==='ip'?window.SS.ipStr(s.ans):String(s.ans))")
    for s in steps: pg.fill('#wsin',s); pg.press('#wsin','Enter'); pg.wait_for_timeout(30)
    ok(pg.inner_text('.fc-q')=='Row 1 network','finishing the steps answers the question and moves on')
    ok(pg.locator('.fs-h').count()==1,'the hinted question is marked with 💡')
    pg.fill('#fin','1.2.3.4'); pg.press('#fin','Enter'); pg.click('#freveal')
    ok(pg.inner_text('.fc-q')=='Row 1 broadcast','“Show the answer” fills it in and moves on')
    for a in answers(pg)[5:]: answer(pg,a); pg.wait_for_timeout(20)
    fb=pg.inner_text('#feedback')
    ok('right on the first try' in fb and 'bad' in pg.get_attribute('#feedback','class'),f'finished sheet is scored on first tries: “{fb[:60]}”')
    ok(pg.locator('.ci').count()==2 and 'you put 240' in pg.inner_text('#work'),'the summary explains each first-try miss, with what you typed')
    pg.click('#checkBtn')
    print('Typos in the copied octets')
    pg.evaluate("window.SS.next(window.SS.genSheet({ip:'10.113.133.211',p:25,asPrefix:false}))")
    for a in answers(pg)[:4]: answer(pg,a)
    pg.fill('#fin','10.133.133.0'); pg.press('#fin','Enter'); pg.wait_for_timeout(40); msg=pg.inner_text('.fc-msg')
    ok('octet 2 should be 113, not 133' in msg and 'different row' not in msg,'a typo in a copied octet is called a typo, not a wrong row')
    pg.fill('#fin','10.113.133.128'); pg.press('#fin','Enter'); pg.wait_for_timeout(40); msg=pg.inner_text('.fc-msg')
    ok('different row' in msg and '(0, 128)' in msg and '256' not in msg,'a real wrong row still says so, listing only valid networks (0, 128)')
    pg.click('#checkBtn') if pg.is_visible('#checkBtn') else None
    print('Other multi-part questions')
    pg.click('.tab[data-m="detective"]')
    while pg.evaluate("window.SS.state.q.fields.length")<2: pg.click('#skipBtn')
    ok(pg.is_visible('#fcard') and pg.inner_text('.fc-q')=='Subnet (network)','Subnet Chart also goes one at a time, network first')
    for a in answers(pg): answer(pg,a)
    ok('good' in pg.get_attribute('#feedback','class'),'Subnet Chart scores when finished')
    pg.click('#checkBtn'); pg.click('.tab[data-m="binary"]')
    ok(pg.is_visible('#fields') and pg.is_hidden('#flow'),'single-box questions show the box straight away')
    pg.click('.tab[data-m="worksheet"]')
    print('Full sheet layout')
    pg.click('#layoutSeg button[data-v="sheet"]'); ok(pg.is_visible('#fields') and pg.is_hidden('#flow'),'Full sheet shows every box at once')
    pg.reload(); pg.wait_for_timeout(300); ok(pg.is_visible('#fields'),'layout choice is remembered')
    pg.click('#layoutSeg button[data-v="flow"]'); ok(pg.is_visible('#fcard'),'switching back works')
    print('Your own problem and share links')
    pg.click('#ownBtn'); pg.fill('#ownIp','10.10.10.64'); pg.fill('#ownMask','255.255.255.224'); pg.click('#ownGo')
    ok('10.10.10.64' in pg.inner_text('#prompt') and '255.255.255.224' in pg.inner_text('#prompt'),'loads the exact IP and mask you type')
    link=pg.input_value('#ownLink'); ok('ip=10.10.10.64' in link and 'mask=255.255.255.224' in link,'gives a share link for that problem')
    for ip,m,expect in [('10.10.10.300','/27','IP address isn’t valid'),('10.10.10.5','/24','/25'),('10.10.10.5','255.0.255.0','mask isn’t valid'),('127.0.0.1','/27','Class A, B or C'),('<b>x</b>','/27','isn’t valid')]:
        pg.fill('#ownIp',ip); pg.fill('#ownMask',m); pg.click('#ownGo'); ok(expect in pg.inner_text('#ownMsg'),f'rejects {ip} {m}')
    p2=b.new_page(); e2=[]; p2.on('pageerror',lambda e:e2.append(str(e))); p2.goto(link); p2.wait_for_timeout(300)
    ok('10.10.10.64' in p2.inner_text('#prompt') and p2.evaluate("window.SS.state.mode")=='worksheet','opening the share link loads that problem')
    p2.goto(URL+'?ip=%3Cimg%20src%3Dx%20onerror%3Dwindow.__p%3D1%3E&mask=%3Cscript%3E'); p2.wait_for_timeout(300)
    ok(not p2.evaluate("!!window.__p") and not e2 and p2.locator('#prompt').inner_text()!='','a malformed or malicious link is ignored safely')
    p2.goto(URL+'?ip=10.10.10.18&mask=29&layout=sheet'); p2.wait_for_timeout(300)
    ok(p2.is_visible('#fields') and '10.10.10.18/29' in p2.inner_text('#prompt'),'a link can also choose the Full sheet layout')
    print('Printing and Present mode')
    pg.click('#printBtn'); ok(pg.is_visible('#prN'),'Print opens its options')
    pg.evaluate("window.SS.buildPrint(6,true,false)")
    ok(pg.locator('#printArea .pp').count()==12 and pg.locator('#printArea .pp-key').count()==1,'6 problems plus a 6-problem answer key')
    blanks=pg.evaluate("[...document.querySelectorAll('#printArea > section .pp-a')].every(td=>!/\\d/.test(td.textContent))")
    keyfilled=pg.evaluate("[...document.querySelectorAll('#printArea .pp-key .pp-a')].every(td=>td.textContent.trim()!=='')")
    ok(blanks and keyfilled,'the worksheet pages are blank and the key is filled in')
    pg.evaluate("document.body.classList.add('printing')"); pg.emulate_media(media='print'); pg.pdf(path='/tmp/sprint_print.pdf',format='Letter'); pg.emulate_media(media='screen'); pg.evaluate("document.body.classList.remove('printing')")
    import fitz
    d=fitz.open('/tmp/sprint_print.pdf'); per=[len([x for x in d[k].get_text('blocks') if x[4].startswith('Problem')]) for k in range(len(d))]
    ok(len(d)==6 and all(n==2 for n in per),f'prints two problems per page ({len(d)} pages: {per})')
    pg.click('#presentBtn'); ok(pg.is_hidden('#tools') and pg.evaluate("document.body.classList.contains('present')"),'Present hides the side panel and enlarges the problem')
    pg.click('#presentBtn')
    print('Security')
    pg.evaluate("window.SS.next(window.SS.genSheet({ip:'10.10.10.18',p:29,asPrefix:true}))")
    pays=['<img src=x onerror="window.__p=1">','"><svg onload="window.__p=1">','</s><b id=inj>x</b>']
    for pay in pays: pg.fill('#fin',pay); pg.press('#fin','Enter'); pg.wait_for_timeout(30)
    pg.click('#fhint')
    for pay in pays: pg.fill('#wsin',pay); pg.press('#wsin','Enter'); pg.wait_for_timeout(30)
    pg.click('#freveal')
    for a in answers(pg)[1:]: answer(pg,a)
    ok(not pg.evaluate("!!window.__p||!!document.getElementById('inj')") and '&lt;img' in pg.inner_html('#work'),'code typed into the one-at-a-time boxes and hint steps is shown as text, never run')
    pg.click('#checkBtn')
    print('Phone')
    m=b.new_page(viewport={'width':360,'height':800},is_mobile=True,has_touch=True); m.goto(URL); m.wait_for_timeout(300)
    m.evaluate("window.SS.next(window.SS.genSheet({ip:'192.168.200.130',p:25,asPrefix:false}))"); widest=0
    for a in answers(m):
        answer(m,a); widest=max(widest,m.evaluate("document.documentElement.scrollWidth"))
    ok(widest<=360,f'a whole worksheet fits a 360px phone the entire way through ({widest}px)')
    ok(not errs,f'no page errors {errs}')
print(f'\n{"all passed" if not fails else str(len(fails))+" failed"}'); sys.exit(1 if fails else 0)
